# # 1.
# # Install Python (latest version) and VS Code on your computer, then take a screenshot of both the Python installation confirmation and the VS Code welcome screen.




# Step 1: Download Python

# 1. Open Google Chrome.
# 2. Go to [https://www.python.org/downloads/](https://www.python.org/downloads/?utm_source=chatgpt.com)
# 3. Click on Download Python.
# 4. Download the latest stable version for Windows.

# Step 2: Install Python

# 1. Open the downloaded Python installer.
# 2. Tick Add Python to PATH if available.
# 3. Click on Install Now or Install.
# 4. Wait for installation to complete.
# 5. Click Close or Finish.

# Step 3: Check Python Installation

# 1. Press `Windows + R`.
# 2. Type `cmd` and press Enter.
# 3. Enter the command:

# ```
# python --version
# ```

# 4\. If the Python version appears, installation is successful.

# Step 4: Take Screenshot

# 1. Keep Command Prompt open with the Python version displayed.
# 2. Press `Windows + Shift + S`.
# 3. Capture the screen.
# 4. Save as `Python_Installation.png`.

# ## Part 2: VS Code Installation

# Step 5: Download VS Code

# 1. Open Google Chrome.
# 2. Go to [https://code.visualstudio.com/download](https://code.visualstudio.com/download?utm_source=chatgpt.com)
# 3. Click Download for Windows.
# 4. Wait for the download to complete.

# Step 6: Install VS Code

# 1. Open the downloaded VS Code setup file.
# 2. Accept the License Agreement.
# 3. Click Next.
# 4. Select Add to PATH.
# 5. Click Install.
# 6. After installation, click Finish.

# Step 7: Open VS Code

# 1. Open Visual Studio Code.
# 2. Wait for the Welcome Screen.
# 3. If it does not appear, click Help → Welcome.

# Step 8: Take Screenshot

# 1. Keep the VS Code Welcome Screen open.
# 2. Press `Windows + Shift + S`.
# 3. Capture the screen.
# 4. Save as `VS_Code_Welcome.png`.

